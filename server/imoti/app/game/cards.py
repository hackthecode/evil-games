def deck_of(card_id: str) -> str:
    """Тестето, от което произхожда картата."""
    card = all_cards().get(card_id)
    return card.deck if card is not None else "community"


@dataclass
class Deck:
    """Разбъркано тесте с цикъл на теглене.

    Картите „освобождаване от проверка" се изваждат от тестето, докато
    играчът не ги използва — тогава се връщат на дъното.
    """

    deck_id: str
    draw_pile: list[str] = field(default_factory=list)
    discard_pile: list[str] = field(default_factory=list)

    @classmethod
    def build(cls, deck_id: str, rng: random.Random) -> "Deck":
        """Създава ново разбъркано тесте."""
        source = COMMUNITY_CARDS if deck_id == "community" else BUSINESS_CARDS
        ids = [c.card_id for c in source]
        rng.shuffle(ids)
        return cls(deck_id=deck_id, draw_pile=ids)

    def draw(self, rng: random.Random) -> Card:
        """Тегли следващата карта; при изчерпване разбърква отново отпадналите."""
        if not self.draw_pile:
            self.draw_pile = list(self.discard_pile)
            self.discard_pile = []
            rng.shuffle(self.draw_pile)
        card_id = self.draw_pile.pop(0)
        return all_cards()[card_id]

    def discard(self, card_id: str) -> None:
        """Връща карта на дъното на тестето."""
        self.discard_pile.append(card_id)

    def to_dict(self) -> dict[str, Any]:
        return {
            "deck_id": self.deck_id,
            "draw_pile": list(self.draw_pile),
            "discard_pile": list(self.discard_pile),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Deck":
        return cls(
            deck_id=data["deck_id"],
            draw_pile=list(data.get("draw_pile", [])),
            discard_pile=list(data.get("discard_pile", [])),
        )
