"""Оригинални тестета карти за „Имоти и Империи".

Две тестета: „Обществено събитие" и „Бизнес възможност" — по 32 оригинални
карти с български текстове, създадени специално за тази игра.

Всяка карта има ``effect`` — речник, който engine-ът интерпретира:

* ``gain`` — получаване на сума от банката;
* ``pay`` — плащане на сума към банката;
* ``move_to`` — преместване до конкретно поле (с доход при преминаване);
* ``nearest_transport`` / ``nearest_utility`` — движение до най-близкия обект
  със специално изчисляване на наема;
* ``move_by`` — преместване с определен брой позиции (може и назад);
* ``repair`` — плащане за ремонт според броя подобрения;
* ``pay_each`` — плащане към всеки друг играч;
* ``collect_each`` — получаване от всеки друг играч;
* ``jail_free`` — карта „освобождаване от проверка" (пази се);
* ``goto_jail`` — изпращане на административна проверка;
* ``extra_turn`` — допълнителен ход;
* ``rent_discount`` — следващият платен наем е наполовина;
* ``start_bonus`` — следващият доход от началния площад е двоен;
* ``keep`` — карта, която остава в ръката на играча и се прилага САМА при
  следващото подходящо действие (виж ``KEEPABLE_POWERS``);
* ``choice`` — карта с избор: сигурен вариант или залог на зар. Сумите в
  ``safe``/``risky`` са със знак — положително печели, отрицателно плаща.
  Четен зар печели (``win``), нечетен губи (``lose``).

Държаните карти се прилагат автоматично, а не по избор на играча. Причината
е, че и компютърните играчи ги държат: при ръчно активиране ботовете щяха да
ги трупат, без никога да ги изиграят.
"""
