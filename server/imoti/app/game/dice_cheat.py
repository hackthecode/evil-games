"""Скрит канал за задаване на следващото хвърляне (само за локална игра).

Външна конзола (``cheat_dice.py`` в корена на проекта) записва желаните зарове
във файла ``data/.dice_next``. При следващото хвърляне двигателят прочита
файла, изтрива го и използва стойностите вместо случайните.

Ако файлът липсва — а това е обичайното състояние — играта работи напълно
нормално и никой ред тук не се задейства. Подмяната става преди съставянето на
събитието за зарове, така че нито то, нито логът, нито интерфейсът се различават
по какъвто и да е начин от истинско хвърляне.
"""
from __future__ import annotations

from pathlib import Path

# Пътят се изчислява от местоположението на модула, а не от работната
# директория, защото сървърът и конзолата са отделни процеси.
SIGNAL_FILE = Path(__file__).resolve().parents[2] / "data" / ".dice_next"


def take_pending() -> tuple[int, int] | None:
    """Връща зададената двойка зарове и я изтрива (важи за едно хвърляне).

    Всяка грешка се поглъща тихо: при повреден или непълен файл играта просто
    продължава със случайни зарове.
    """
    try:
        raw = SIGNAL_FILE.read_text(encoding="utf-8")
    except OSError:
        return None

    # Изтриваме веднага, за да не остане да важи и за следващия ход, дори ако
    # съдържанието се окаже невалидно.
    try:
        SIGNAL_FILE.unlink()
    except OSError:
        pass

    parts = raw.split()
    if len(parts) != 2:
        return None
    try:
        die1, die2 = int(parts[0]), int(parts[1])
    except ValueError:
        return None
    if 1 <= die1 <= 6 and 1 <= die2 <= 6:
        return die1, die2
    return None
